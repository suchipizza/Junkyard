"""Export JSON Schemas for every record type into ``schemas/``.

Usage::

    python -m junkyard.models.export            # write schemas/
    python -m junkyard.models.export --check    # exit 1 if schemas/ is stale

Output is deterministic (sorted keys, fixed indent) so CI can diff it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pydantic import BaseModel

from junkyard import SCHEMA_VERSION
from junkyard.models import (
    ActuatorClassesFile,
    Assembly,
    BrickManifest,
    CategoriesFile,
    FunctionsFile,
    MaterialsFile,
    MechanismRecord,
    PartRecord,
    PortsFile,
    Sidecar,
)

SCHEMA_BASE_URL = "https://github.com/suchipizza/Junkyard/blob/main/schemas/"

#: File name -> (model, title)
SCHEMAS: dict[str, tuple[type[BaseModel], str]] = {
    "brick.schema.json": (BrickManifest, "Junkyard brick manifest (brick.yaml)"),
    "part.schema.json": (PartRecord, "Junkyard part record"),
    "mechanism.schema.json": (MechanismRecord, "Junkyard Atlas mechanism record"),
    "assembly.schema.json": (Assembly, "Junkyard assembly.json"),
    "sidecar.schema.json": (Sidecar, "Junkyard generated-file sidecar (<file>.junkyard.json)"),
    "vocab.functions.schema.json": (FunctionsFile, "Junkyard functions vocabulary"),
    "vocab.ports.schema.json": (PortsFile, "Junkyard port types vocabulary"),
    "vocab.actuator_classes.schema.json": (ActuatorClassesFile, "Junkyard actuator classes"),
    "vocab.categories.schema.json": (CategoriesFile, "Junkyard brick categories"),
    "vocab.materials.schema.json": (MaterialsFile, "Junkyard materials vocabulary"),
}


def render_schemas() -> dict[str, str]:
    """Return ``{file name: JSON text}`` for every schema."""
    out: dict[str, str] = {}
    for name, (model, title) in SCHEMAS.items():
        schema = model.model_json_schema(by_alias=True, mode="validation")
        schema = {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": SCHEMA_BASE_URL + name,
            "$comment": "Generated by `python -m junkyard.models.export`. Do not hand-edit.",
            "x-junkyard-schema-version": SCHEMA_VERSION,
            **schema,
            "title": title,
        }
        out[name] = json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    return out


def stale_schemas(directory: Path) -> list[str]:
    """Names of schema files that are missing, different or unexpected in ``directory``."""
    wanted = render_schemas()
    stale = [n for n, text in wanted.items() if _read(directory / n) != text]
    extra = [p.name for p in directory.glob("*.json") if p.name not in wanted]
    return sorted(stale + extra)


def write_schemas(directory: Path) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    for p in directory.glob("*.json"):
        if p.name not in SCHEMAS:
            p.unlink()
    written = []
    for name, text in render_schemas().items():
        path = directory / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.exists() else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=Path("schemas"))
    parser.add_argument("--check", action="store_true", help="fail if schemas are stale")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_schemas(args.out)
        if stale:
            print(
                f"Stale schemas in {args.out}/: {', '.join(stale)}\n"
                "Run `python -m junkyard.models.export` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"{len(SCHEMAS)} schemas up to date in {args.out}/")
        return 0
    for path in write_schemas(args.out):
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
